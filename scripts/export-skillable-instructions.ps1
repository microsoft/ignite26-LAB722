function Convert-InstructionContent {
    param([Parameter(Mandatory)] [string] $SourcePath)

    $content = [IO.File]::ReadAllText($SourcePath).Replace("`r`n", "`n")
    if ((Split-Path $SourcePath -Leaf) -eq '02-configure-orchestrator.md') {
        $original = '$controllerPython = (Get-Command python -CommandType Application |' +
            "`n" + '    Select-Object -First 1).Source'
        if (-not $content.Contains($original)) {
            throw 'The controller snippet changed; review the Skillable runtime adaptation.'
        }
        $content = $content.Replace($original,
            '$controllerPython = Join-Path $env:LOCALAPPDATA ''Caldova\venvs\controller\Scripts\python.exe''')
    }

    $sourceDirectory = Split-Path $SourcePath -Parent
    $insideCode = $false
    $lines = foreach ($line in $content.Split("`n")) {
        if ($line -match '^```') {
            $insideCode = -not $insideCode
            $line
            continue
        }
        if ($insideCode) {
            $line
            continue
        }
        if ($line -match '!\[[^\]]*\]\((?!https?://)') {
            throw "Stage relative images explicitly before exporting: $SourcePath"
        }
        [regex]::Replace($line, '(?<!!)\[(?<label>[^\]\r\n]+)\]\((?<target>[^)\r\n]+)\)', {
            param($match)
            $target = $match.Groups['target'].Value
            if ($target -match '^(https?://|#)') {
                return $match.Value
            }
            $parts = $target.Split('#', 2)
            $path = [IO.Path]::GetFullPath(
                (Join-Path $sourceDirectory $parts[0].Replace('/', '\')))
            $prefix = $repositoryRoot + [IO.Path]::DirectorySeparatorChar
            if (-not $path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
                throw "Instruction link escapes the repository: $target"
            }
            if ($path -ne $outputFile -and -not (Test-Path -LiteralPath $path)) {
                throw "Instruction link is missing: $target"
            }
            $relative = [IO.Path]::GetRelativePath($repositoryRoot, $path)
            $section = if ($parts.Count -eq 2) { "; section: ``$($parts[1])``" } else { '' }
            return "$($match.Groups['label'].Value) (VM file: ``$relative``$section)"
        })
    }
    if ($insideCode) {
        throw "Unclosed code fence: $SourcePath"
    }
    return ($lines -join "`n").TrimEnd()
}

