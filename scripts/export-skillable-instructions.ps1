[CmdletBinding()]
param(
    [string] $OutputPath = (Join-Path $PSScriptRoot '..\instructions\skillable.md')
)

$ErrorActionPreference = 'Stop'
$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$outputFile = [IO.Path]::GetFullPath($OutputPath)
$sources = @(
    'instructions\README.md'
    'instructions\00-welcome-and-readiness.md'
    'instructions\01-open-research-portal.md'
    'instructions\02-configure-orchestrator.md'
    'instructions\03-prepare-sandbox.md'
    'instructions\04-run-agent-team.md'
    'instructions\05-build-and-publish.md'
    'instructions\06-trace-the-evidence.md'
    'instructions\worksheet.md'
)

function Convert-InstructionContent {
    param([Parameter(Mandatory)] [string] $SourcePath)

    $content = [IO.File]::ReadAllText($SourcePath).Replace("`r`n", "`n")
    $sourceDirectory = Split-Path $SourcePath -Parent
    $insideCode = $false
    $lines = foreach ($line in $content.Split("`n")) {
        if ($line -match '^(?:> ?)?```') {
            $insideCode = -not $insideCode
            $line
            continue
        }
        if ($insideCode) {
            if (($line -replace '^> ?', '') -ceq '<!-- pagebreak -->') {
                throw "Page break inside a code fence: $SourcePath"
            }
            $line
            continue
        }
        [regex]::Replace($line, '(?<image>!)?\[(?<label>[^\]\r\n]+)\]\((?<target>[^)\r\n]+)\)', {
            param($match)
            $target = $match.Groups['target'].Value
            if ($target -match '^(https?://|#)') {
                return $match.Value
            }
            $parts = $target.Split('#', 2)
            $path = [IO.Path]::GetFullPath(
                (Join-Path $sourceDirectory $parts[0].Replace('/', '\')))
            $prefix = $repositoryRoot + [IO.Path]::DirectorySeparatorChar
            if (-not $path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
                throw "Instruction link escapes the repository: $target"
            }
            if ($path -ne $outputFile -and -not (Test-Path -LiteralPath $path)) {
                throw "Instruction link is missing: $target"
            }
            $relative = [IO.Path]::GetRelativePath($repositoryRoot, $path)
            if ($match.Groups['image'].Success) {
                if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
                    throw "Instruction image is missing: $target"
                }
                if ([IO.Path]::GetExtension($path) -ine '.png') {
                    throw "Instruction screenshot must be a PNG: $target"
                }
                $image = [Convert]::ToBase64String([IO.File]::ReadAllBytes($path))
                return "![$($match.Groups['label'].Value)](data:image/png;base64,$image)"
            }
            $section = if ($parts.Count -eq 2) { "; section: ``$($parts[1])``" } else { '' }
            return "$($match.Groups['label'].Value) (VM file: ``$relative``$section)"
        })
    }
    if ($insideCode) {
        throw "Unclosed code fence: $SourcePath"
    }
    return ($lines -join "`n").TrimEnd()
}

$welcome = @'
<!-- Generated by scripts\export-skillable-instructions.ps1. Edit its sources, then regenerate. -->
# @lab.Title

## 1.1 Welcome

In this lab, you will use an agent team to complete and deploy Caldova's research application.

Select @lab.VirtualMachine(Win11-Pro-Base).SelectLink and sign in to the Windows VM:

- Username: +++@lab.VirtualMachine(Win11-Pro-Base).Username+++
- Password: +++@lab.VirtualMachine(Win11-Pro-Base).Password+++

Your tools and code are already on the VM. Use the **Resources** tab for your Azure credentials and subscription.

'@

$pages = @($welcome.Replace("`r`n", "`n").TrimEnd()) + @(foreach ($relative in $sources) {
    $content = Convert-InstructionContent -SourcePath (Join-Path $repositoryRoot $relative)
    foreach ($page in [regex]::Split($content, '(?m)^<!-- pagebreak -->$')) {
        if ($page.Trim() -notmatch '^# [^\r\n]+') {
            throw "Each instruction page must start with a title: $relative"
        }
        $page.Trim()
    }
})
$manual = ($pages -join "`n`n===`n`n") + "`n"
[void] [IO.Directory]::CreateDirectory((Split-Path $outputFile -Parent))
[IO.File]::WriteAllText($outputFile, $manual, [Text.UTF8Encoding]::new($false))
[pscustomobject] @{
    Path = $outputFile
    Pages = $pages.Count
    Bytes = (Get-Item -LiteralPath $outputFile).Length
    Sha256 = (Get-FileHash -LiteralPath $outputFile -Algorithm SHA256).Hash.ToLowerInvariant()
}
